"""Assemble eval/report.md from whatever results exist in eval/results/; missing steps get a one-line placeholder.

CLI: python eval/report.py
"""

import argparse
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from backend.app.config import Settings, get_settings
from backend.app.evaluation import grounding, latency, rating, retrieval_eval, usability
from backend.app.evaluation.common import read_json


def _threshold_section(result: dict[str, Any]) -> str:
    """Current vs recommended threshold and their confusion counts."""
    rows = [("current", result["current"]), ("recommended", result["recommended"])]
    lines = [
        f"In-corpus questions: {result['n_in']}; out-of-corpus: {result['n_out']}; null when fewer than {result['k']} "
        "reranked chunks reach the threshold. Positive class = should be null.",
        "",
        "| | Threshold | Precision | Recall | F1 | In-corpus refused | Out-of-corpus answered |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {name} | {p['threshold']} | {p['precision']:.2f} | {p['recall']:.2f} | {p['f1']:.2f} "
        f"| {p['fp']} | {p['fn']} |"
        for name, p in rows
    ]
    return "\n".join(lines) + "\n"


SECTIONS: tuple[tuple[str, str, str, Callable[[Any], str]], ...] = (
    ("Retrieval: FAISS vs BM25 vs hybrid", "retrieval.json", "run_retrieval.py", retrieval_eval.render_markdown),
    ("Null-response threshold", "threshold.json", "tune_threshold.py", _threshold_section),
    ("Functional run: automatic grounding checks", "grounding.json", "grounding_check.py", grounding.render),
    ("Human grounding ratings: agreement", "agreement.json", "agreement.py", rating.render),
    ("Usability survey", "usability.json", "analyze_usability.py", usability.render),
    ("Latency", "latency.json", "bench_latency.py", lambda r: f"```\n{latency.render(r)}\n```\n"),
)


def build_report(results_dir: Path) -> str:
    """Markdown report with one section per evaluation step, in pipeline order."""
    parts = [
        "# HakiAI evaluation report",
        "",
        "Generated by `python eval/report.py` from the files in eval/results/. Sections without results say which "
        "script produces them.",
    ]
    for title, filename, script, render in SECTIONS:
        path = results_dir / filename
        body = render(read_json(path)) if path.exists() else f"_Not available yet: run `python eval/{script}`._\n"
        parts += ["", f"## {title}", "", body.rstrip()]
    return "\n".join(parts) + "\n"


def main(argv: Sequence[str] | None = None, settings: Settings | None = None) -> int:
    """CLI: write eval/report.md (always succeeds; missing results are noted in the report)."""
    argparse.ArgumentParser(description="Assemble eval/report.md from eval/results/.").parse_args(argv)
    settings = settings or get_settings()
    report = build_report(settings.eval_results_dir)
    settings.eval_report_path.parent.mkdir(parents=True, exist_ok=True)
    settings.eval_report_path.write_text(report, encoding="utf-8")
    present = sum((settings.eval_results_dir / filename).exists() for _, filename, _, _ in SECTIONS)
    print(f"wrote {settings.eval_report_path} ({present} of {len(SECTIONS)} sections have results)")
    return 0
